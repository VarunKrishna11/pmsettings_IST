def _load_config(config_path: str) -> dict:
    """
    Load config from JSON or Excel file.

    Supports both .json and .xlsx formats. The xlsx format is generated
    by generate_smelt_config.py alongside the JSON and contains 3 sheets:
      - settings: key-value pairs (ist_base, smelt_root, target_configs, etc.)
      - smelt_entries: folder_base, ist_modes, note, candidates
      - user_groups: group_id, ist_modes
    """
    ext = os.path.splitext(config_path)[1].lower()

    if ext == '.json':
        with open(config_path, 'r', encoding='utf-8') as f:
            return json.load(f)

    if ext == '.xlsx':
        try:
            import openpyxl
        except ImportError:
            print("ERROR: openpyxl required to read .xlsx config. Install: pip install openpyxl")
            return {}

        wb = openpyxl.load_workbook(config_path, data_only=True)
        config = {}

        # ── Read settings sheet ──
        if 'settings' in wb.sheetnames:
            ws = wb['settings']
            kv = {}
            for row in ws.iter_rows(min_row=2, max_col=2, values_only=True):
                key, val = row
                if key:
                    kv[str(key).strip()] = str(val).strip() if val else ''

            # Per-family SMELT roots
            smelt_roots = {}
            for k, v in kv.items():
                if k.startswith('smelt_root_') and v:
                    fam = k[len('smelt_root_'):]
                    smelt_roots[fam] = v
            config['inputs'] = {
                'ist_base': kv.get('ist_base', 'ist_settings.pm'),
                'smelt_roots': smelt_roots if smelt_roots else {},
                'xlsx': kv.get('xlsx', 'IST_Modes_Support.xlsx'),
            }
            # Legacy single smelt_root fallback
            if not smelt_roots and kv.get('smelt_root'):
                config['inputs']['smelt_root'] = kv['smelt_root']
            target_configs_str = kv.get('target_configs', '')
            families_str = kv.get('target_families', kv.get('target_family', 'MATHS-IST'))
            families_list = [f.strip() for f in families_str.split('|') if f.strip()]
            config['target'] = {
                'configs': [c.strip() for c in target_configs_str.split('|') if c.strip()],
                'families': families_list,
            }

        # ── Read smelt_entries sheet ──
        entries = []
        if 'smelt_entries' in wb.sheetnames:
            ws = wb['smelt_entries']
            headers = [ws.cell(1, c).value for c in range(1, ws.max_column + 1)]
            col_map = {str(h).strip(): i for i, h in enumerate(headers) if h}

            for row in ws.iter_rows(min_row=2, max_col=ws.max_column, values_only=True):
                folder_base = str(row[col_map.get('folder_base', 0)] or '').strip()
                if not folder_base:
                    continue
                family_val = str(row[col_map.get('family', -1)] or '').strip() if 'family' in col_map else ''
                ist_modes_str = str(row[col_map.get('ist_modes', 1)] or '').strip()
                ist_modes = [m.strip() for m in ist_modes_str.split('|') if m.strip()]
                note = str(row[col_map.get('note', 2)] or '').strip()
                entry = {
                    'folder_base': folder_base,
                    'ist_modes': ist_modes,
                    'note': note,
                }
                if family_val:
                    entry['family'] = family_val
                entries.append(entry)
        config['smelt_entries'] = entries

        # ── Read user_groups sheet ──
        groups = []
        if 'user_groups' in wb.sheetnames:
            ws = wb['user_groups']
            for row in ws.iter_rows(min_row=2, max_col=2, values_only=True):
                group_id, ist_modes_str = row
                if ist_modes_str:
                    modes = [m.strip() for m in str(ist_modes_str).split('|') if m.strip()]
                    if modes:
                        groups.append({'ist_modes': modes})
        config['user_groups'] = groups

        print(f"  Loaded config from Excel: {config_path}")
        return config

    print(f"ERROR: Unsupported config format '{ext}'. Use .json or .xlsx")
    return {}


def run_update(
    config_path: str,
    verbose: bool = False,
    dry_run: bool = False,
    preview: bool = False,
) -> int:
    """Apply SMELT coefficient updates based on config file."""

    # Load config (supports both .json and .xlsx)
    config = _load_config(config_path)
    if not config:
        return 1

    inputs = config.get('inputs', {})
    ist_base_path = inputs.get('ist_base', 'ist_settings.pm')
    target_configs = config.get('target', {}).get('configs', [])
    # Support both 'families' (list) and legacy 'family' (string)
    target = config.get('target', {})
    target_families = target.get('families', [])
    if not target_families:
        legacy = target.get('family', 'MATHS-IST')
        target_families = [legacy] if isinstance(legacy, str) else legacy
    smelt_entries = config.get('smelt_entries', [])
    user_groups = config.get('user_groups', [])

    # Resolve paths relative to config file directory
    config_dir = os.path.dirname(os.path.abspath(config_path))
    if not os.path.isabs(ist_base_path):
        ist_base_path = os.path.join(config_dir, ist_base_path)

    # Resolve per-family SMELT roots
    raw_smelt_roots = inputs.get('smelt_roots', {})
    smelt_roots: Dict[str, str] = {}
    for fam, root in raw_smelt_roots.items():
        if os.path.isabs(root):
            smelt_roots[fam] = root
        else:
            smelt_roots[fam] = os.path.join(config_dir, root)
    # Legacy single smelt_root: apply to all families
    if not smelt_roots and inputs.get('smelt_root'):
        legacy_root = inputs['smelt_root']
        if not os.path.isabs(legacy_root):
            legacy_root = os.path.join(config_dir, legacy_root)
        for fam in target_families:
            smelt_roots[fam] = legacy_root

    # Create timestamped output folder under pmsettings_IST/output/
    timestamp = datetime.now().strftime('%Y%m%d_%H%M%S')
    output_folder = os.path.join(_PROJECT_ROOT, 'output', timestamp)
    output_pm_path = os.path.join(output_folder, 'ist_settings.pm')
    output_xlsx_path = os.path.join(output_folder, 'ist_settings.xlsx')

    # Validate
    if not os.path.isfile(ist_base_path):
        print(f"ERROR: Base file not found: {ist_base_path}")
        print(f"  Paths in config are resolved relative to config dir: {config_dir}")
        return 1

    # Filter out entries with empty ist_modes
    valid_entries = [e for e in smelt_entries if e.get('ist_modes')]
    skipped = len(smelt_entries) - len(valid_entries)
    if skipped:
        print(f"WARNING: Skipping {skipped} entries with empty ist_modes")

    mode_label = "PREVIEW" if preview else ("DRY RUN" if dry_run else "APPLY")
    print(f"Mode:      {mode_label}")
    print(f"Input:     {ist_base_path}")
    for fam, root in smelt_roots.items():
        print(f"SMELT:     {fam} -> {root}")
    if not preview and not dry_run:
        print(f"Output:    {output_folder}/")
    print(f"Configs:   {target_configs}")
    print(f"Families:  {target_families}")
    print(f"Entries:   {len(valid_entries)} SMELT, {len(user_groups)} groups")
    print()

    # Read base file
    with open(ist_base_path, 'r', encoding='utf-8') as f:
        file_text = f.read()

    # Build per-family SMELT coefficient maps
    print("Reading SMELT coefficients...")
    smelt_maps: Dict[str, Dict[Tuple[str, str], List[str]]] = {}
    total_mapped = 0
    for family in target_families:
        fam_map = build_smelt_map(valid_entries, smelt_roots, family, verbose=verbose)
        smelt_maps[family] = fam_map
        total_mapped += len(fam_map)
        if fam_map:
            print(f"  {family}: {len(fam_map)} (mode, rail) pairs")
        else:
            print(f"  {family}: no SMELT coefficients (SMELT data may not exist yet)")

    print(f"  Total: {total_mapped} (mode, rail) pairs\n")

    if total_mapped == 0:
        print("ERROR: No valid SMELT coefficients found across any family. Check config entries.")
        return 1

    # Process each target config x family
    for config_name in target_configs:
        print(f"Processing config: {config_name}")

        for family in target_families:
            handler = FAMILY_HANDLERS.get(family)
            if not handler:
                print(f"  WARNING: No handler for family '{family}', skipping")
                continue

            smelt_map = smelt_maps.get(family, {})
            if not smelt_map:
                print(f"  {family}: no SMELT data available, skipping")
                continue

            existing_vfes = parse_vfes(file_text, config_name, family=family)
            if not existing_vfes:
                print(f"  {family}: no VFEs found, skipping")
                continue

            total_modes = sum(len(v['modes']) for v in existing_vfes)
            print(f"  {family}: {len(existing_vfes)} existing VFEs, {total_modes} mode entries")

            new_vfes = handler.plan_new_vfes(existing_vfes, smelt_map, user_groups, verbose=verbose)

            smelt_count = sum(1 for v in new_vfes if v['source'] == 'smelt')
            residual_count = sum(1 for v in new_vfes if v['source'] == 'residual')
            original_count = sum(1 for v in new_vfes if v['source'] == 'original')
            print(f"    -> {len(new_vfes)} VFEs "
                  f"({smelt_count} SMELT, {residual_count} residual, {original_count} original)")

            if not dry_run:
                file_text = apply_family_update(file_text, config_name, family, new_vfes, verbose=verbose)

        print()

    # Summary
    print("=" * 60)
    print("SUMMARY")
    print("=" * 60)
    for config_name in target_configs:
        for family in target_families:
            vfes = parse_vfes(file_text, config_name, family=family)
            if vfes:
                print(f"\n  {config_name} / {family}:")
                for v in vfes:
                    rail = classify_rail(v['voltage_domains'])
                    c = v['coeffs']
                    c_short = f"[{c[0]}, ... {c[-1]}]" if len(c) >= 2 else str(c)
                    print(f"    {v['id']:6s}  {rail:6s}  {v['thermeqtype']:12s}  "
                          f"modes={len(v['modes'])}  coeffs={c_short}")

    # ----- Preview mode: generate Excel only -----
    if preview:
        preview_xlsx = os.path.join(config_dir, f'ist_settings_preview_{timestamp}.xlsx')
        _export_to_excel(file_text, preview_xlsx)
        print(f"\n{'=' * 60}")
        print(f"PREVIEW Excel: {preview_xlsx}")
        print(f"Review this file. When satisfied, re-run without --preview to generate the .pm file.")
        return 0

    # ----- Dry run: no output -----
    if dry_run:
        print("\nDRY RUN - no output files written")
        return 0

    # ----- Apply mode: create timestamped output folder -----
    os.makedirs(output_folder, exist_ok=True)

    # Write .pm file
    with open(output_pm_path, 'w', encoding='utf-8') as f:
        f.write(file_text)
    print(f"\nWritten: {output_pm_path}")

    # Generate Excel alongside
    _export_to_excel(file_text, output_xlsx_path)
    print(f"Written: {output_xlsx_path}")

    print(f"\nOutput folder: {output_folder}")
    return 0


