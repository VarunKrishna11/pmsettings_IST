def _export_to_excel(pm_text: str, xlsx_path: str) -> None:
    """Export ist_settings .pm text to a formatted Excel workbook."""
    try:
        import openpyxl
        from openpyxl.styles import Font, Alignment, PatternFill
    except ImportError:
        print("WARNING: openpyxl not installed, skipping Excel export")
        print("  Install with: pip install openpyxl")
        return

    # --- helpers ---
    def _find_block(text, key, start=0):
        pattern = re.compile(rf"'{re.escape(key)}'\s*=>\s*\{{")
        match = pattern.search(text, start)
        if not match:
            return None
        brace_start = match.end() - 1
        depth = 0
        i = brace_start
        while i < len(text):
            ch = text[i]
            if ch == '{':
                depth += 1
            elif ch == '}':
                depth -= 1
                if depth == 0:
                    return match.start(), i + 1
            i += 1
        return None

    def _find_vfe_blocks(block_text):
        results = []
        pat = re.compile(r"'(VFE\d+)'\s*=>\s*\{")
        for m in pat.finditer(block_text):
            vfe_name = m.group(1)
            rel_start = m.start()
            brace_start = m.end() - 1
            depth = 0
            i = brace_start
            while i < len(block_text):
                ch = block_text[i]
                if ch == '{':
                    depth += 1
                elif ch == '}':
                    depth -= 1
                    if depth == 0:
                        results.append((vfe_name, rel_start, i + 1))
                        break
                i += 1
        return results

    def _parse_list(list_text):
        list_text = re.sub(r"#.*", "", list_text)
        raw = [item.strip() for item in list_text.split(",") if item.strip()]
        return [item.strip().strip("'").strip('"') for item in raw]

    def _extract_list(vfe_text, key):
        m = re.search(rf"'{re.escape(key)}'\s*=>\s*\[(.*?)\]", vfe_text, re.S)
        return _parse_list(m.group(1)) if m else []

    def _extract_single(vfe_text, key):
        m = re.search(rf"'{re.escape(key)}'\s*=>\s*'([^']*)'", vfe_text)
        return m.group(1).strip() if m else ""

    def _extract_coeffs(vfe_text):
        m = re.search(r"'Coeffs'\s*=>\s*\[(.*?)\]", vfe_text, re.S)
        return _parse_list(m.group(1)) if m else []

    def _list_top_keys(block_text):
        keys = []
        pat = re.compile(r"'([^']+)'\s*=>\s*\{")
        depth = 0
        depths = [0] * (len(block_text) + 1)
        for i, ch in enumerate(block_text):
            if ch == '{':
                depth += 1
            elif ch == '}':
                depth -= 1
            depths[i + 1] = depth
        for m in pat.finditer(block_text):
            if depths[m.start()] == 1:
                keys.append(m.group(1))
        return keys

    def _detect_source(vfe_text):
        return "SMELT" if '#SMELT' in vfe_text else "Safe"

    # --- build workbook ---
    data_block = _find_block(pm_text, "DataPointers")
    if not data_block:
        print("WARNING: DataPointers block not found, skipping Excel export")
        return
    dp_start, dp_end = data_block
    dp_text = pm_text[dp_start:dp_end]
    configs = _list_top_keys(dp_text)

    wb = openpyxl.Workbook()
    families = ["MATHS-IST", "RIST", "RIST-Adaptive"]
    sheets = {}
    header_font = Font(bold=True)
    header_fill = PatternFill("solid", fgColor="D9E1F2")
    header_align = Alignment(horizontal="center", vertical="center", wrap_text=True)
    cell_align = Alignment(vertical="top", wrap_text=True)
    smelt_fill = PatternFill("solid", fgColor="C6EFCE")
    safe_fill = PatternFill("solid", fgColor="FCE4D6")

    for i, family in enumerate(families):
        ws = wb.active if i == 0 else wb.create_sheet(title=family)
        ws.title = family
        headers = ["Config", "VFE", "Source", "ISTModeNames",
                   "VoltageDomains", "Thermeqtype", "Variable", "Coeffs"]
        ws.append(headers)
        for col_idx in range(1, len(headers) + 1):
            cell = ws.cell(1, col_idx)
            cell.font = header_font
            cell.fill = header_fill
            cell.alignment = header_align
        ws.freeze_panes = "A2"
        sheets[family] = ws

    ws_modes = wb.create_sheet(title="ISTModeRows")
    mode_headers = ["Config", "TestType", "VFE", "Source", "ISTModeName",
                    "VoltageDomains", "Thermeqtype", "Variable", "Coeffs"]
    ws_modes.append(mode_headers)
    for col_idx in range(1, len(mode_headers) + 1):
        cell = ws_modes.cell(1, col_idx)
        cell.font = header_font
        cell.fill = header_fill
        cell.alignment = header_align
    ws_modes.freeze_panes = "A2"

    for cfg in configs:
        config_block = _find_block(pm_text, cfg)
        if not config_block:
            continue
        c_start, c_end = config_block
        config_text = pm_text[c_start:c_end]
        for family in families:
            fam_block = _find_block(config_text, family)
            if not fam_block:
                continue
            f_start, f_end = fam_block
            fam_text = config_text[f_start:f_end]
            for vfe_name, vfe_start, vfe_end in _find_vfe_blocks(fam_text):
                vfe_text = fam_text[vfe_start:vfe_end]
                modes = _extract_list(vfe_text, "ISTModeNames")
                domains = _extract_list(vfe_text, "VoltageDomains")
                thermeq = _extract_single(vfe_text, "Thermeqtype")
                variables = _extract_list(vfe_text, "Variable")
                coeffs = _extract_coeffs(vfe_text)
                source = _detect_source(vfe_text)
                row = [cfg, vfe_name, source, "|".join(modes),
                       "|".join(domains), thermeq, "|".join(variables), "|".join(coeffs)]
                ws_fam = sheets[family]
                ws_fam.append(row)
                row_fill = smelt_fill if source == "SMELT" else safe_fill
                for col_idx in range(1, len(row) + 1):
                    ws_fam.cell(ws_fam.max_row, col_idx).fill = row_fill

                for mode in modes if modes else [""]:
                    mode_row = [cfg, family, vfe_name, source, mode,
                                "|".join(domains), thermeq, "|".join(variables), "|".join(coeffs)]
                    ws_modes.append(mode_row)
                    for col_idx in range(1, len(mode_row) + 1):
                        ws_modes.cell(ws_modes.max_row, col_idx).fill = row_fill

    for ws in list(sheets.values()) + [ws_modes]:
        for row in ws.iter_rows(min_row=2, max_row=ws.max_row):
            for cell in row:
                cell.alignment = cell_align
        if ws.title == "ISTModeRows":
            widths = [24, 16, 10, 8, 40, 28, 16, 28, 60]
        else:
            widths = [24, 10, 8, 60, 28, 16, 28, 60]
        for idx, width in enumerate(widths, start=1):
            ws.column_dimensions[openpyxl.utils.get_column_letter(idx)].width = width

    wb.save(xlsx_path)


