#!/usr/bin/env python3
"""
update_ist_coefficients.py - Apply SMELT Coefficients to IST Settings
======================================================================

Reads a smelt_update_config.json (generated by generate_smelt_config.py),
applies real SMELT-fitted coefficients to ist_settings.pm VFE tables, and
produces updated .pm and .xlsx output files.

Supports multiple IST families: MATHS-IST, RIST, RIST-Adaptive.
Each family has its own handler module that implements parsing, planning,
and Perl text generation.

Workflow:
  Step 1 - Generate config:
    python scripts/generate_smelt_config.py -o config/smelt_update_config.json

  Step 2 - Review & edit config

  Step 3 - Preview:
    python scripts/update_ist_coefficients.py --config smelt_update_config.json --preview

  Step 4 - Apply:
    python scripts/update_ist_coefficients.py --config smelt_update_config.json [--verbose]
"""

